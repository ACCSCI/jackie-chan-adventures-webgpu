const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch({ executablePath: process.env.CH, args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
  const pg = await b.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = []; pg.on('pageerror', e => errs.push(e.message)); pg.on('console', m => { if (m.type() === 'error') errs.push(m.text().slice(0, 200)); });
  await pg.goto(require('node:url').pathToFileURL(require('node:path').resolve(__dirname, '../dist/index.html')).href + '?webgl'); await pg.waitForFunction(() => window.__game && window.__game.SKIN.ready, null, { timeout: 90000 });
  await pg.mouse.click(5, 5); await pg.waitForTimeout(3000);
  const ev = (f) => pg.evaluate(f);
  console.log('menu', await ev(() => { const g = window.__game; return [g.AC && g.AC.state, g.BGM.name, !!g.BGM.cur, g.AudioBus.bgm && +g.AudioBus.bgm.gain.value.toFixed(2)]; }));
  await ev(() => { const g = window.__game; document.getElementById('menu').classList.add('hide'); g.started = true; g.locked = true; g.Story.begin(0); g.step(10); g.BGM.update(1.3); });
  await pg.waitForTimeout(2500);
  console.log('story', await ev(() => { const g = window.__game; return [g.BGM.name, !!g.BGM.cur, !!g.Voice.cur, g.BGM.duck, g.Story.i, Object.keys(g.Voice.cache).length]; }));
  await ev(() => { const g = window.__game; g.Story.next(); g.Story.next(); }); await pg.waitForTimeout(1500);
  console.log('next', await ev(() => { const g = window.__game; return [g.Story.i, !!g.Voice.cur]; }));
  await ev(() => { const g = window.__game; g.Story.skip(); g.step(30); g.BGM.update(1.3); }); await pg.waitForTimeout(3500);
  console.log('fight', await ev(() => { const g = window.__game; return [g.BGM.name, !!g.BGM.cur, g.wave]; }));
  await ev(() => { const g = window.__game; g.Story.begin(8); g.Story.skip(); g.step(30); g.BGM.update(1.3); }); await pg.waitForTimeout(3000);
  console.log('boss', await ev(() => { const g = window.__game; return [g.BGM.name, !!g.BGM.cur]; }));
  const check = await ev(async () => {
    const g = window.__game;
    const names = ['menu', 'calm', 'battle', 'boss', 'temple'];
    const durations = await Promise.all(names.map(async n => [n, (await g.BGM.get(n)).duration]));
    const selection = g.BGM.name === 'boss';
    g.Menu.act('voice'); const off = !g.Voice.on && !g.Voice.cur;
    g.Menu.act('voice'); const on = g.Voice.on;
    g.Menu.act('music'); g.BGM.update(1.3);
    await new Promise(r => setTimeout(r, 1000));
    const muted = g.AudioBus.bgm.gain.value < 0.02;
    g.Menu.act('music'); g.BGM.update(1.3);
    return {durations, selection, off, on, muted};
  });
  console.log('checks', check);
  assert.equal(check.selection, true); assert.equal(check.off, true);
  assert.equal(check.on, true); assert.equal(check.muted, true);
  assert.ok(check.durations.every(x => x[1] > 5));
  console.log(errs.slice(0, 8)); assert.deepEqual(errs, []);
  await b.close(); process.exit(0);
})();
